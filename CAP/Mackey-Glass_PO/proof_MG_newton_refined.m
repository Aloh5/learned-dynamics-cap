% Certify the corrected candidate, then identify it with the original orbit.
% The proof driver clears its workspace, so recover all paths after it runs.
refinement_script_dir=fileparts(mfilename('fullpath'));
if isempty(getenv('MG_FIXED_CAP_OUTPUT_DIR'))
    setenv('MG_FIXED_CAP_OUTPUT_DIR',fullfile(refinement_script_dir,'outputs_newton_refined'));
end
if isempty(getenv('MG_CAP_RADIUS')),setenv('MG_CAP_RADIUS','1.2e-12');end
assert(~strcmp(getenv('MG_FIXED_CAP_OUTPUT_DIR'),fullfile(refinement_script_dir,'outputs_fixed_parameter')),...
    'Refinement must not overwrite the original certificate.');
for stale_name={'newton_refinement_summary.json','newton_refinement_manifest.json'}
    stale_path=fullfile(getenv('MG_FIXED_CAP_OUTPUT_DIR'),stale_name{1});
    if exist(stale_path,'file'),delete(stale_path);end
end
run(fullfile(refinement_script_dir,'proof_MG_fixed_parameter.m'));
refinement_script_dir=fileparts(mfilename('fullpath'));
refinement_out=getenv('MG_FIXED_CAP_OUTPUT_DIR');
original_out=fullfile(refinement_script_dir,'outputs_fixed_parameter');
original=load(fullfile(original_out,'mg_fixed_parameter_candidate.mat'));
corrected=load(fullfile(refinement_out,'mg_fixed_parameter_candidate.mat'));
original_cert=jsondecode(fileread(fullfile(original_out,'mg_fixed_parameter_certificate.json')));
corrected_cert=jsondecode(fileread(fullfile(refinement_out,'mg_fixed_parameter_certificate.json')));
assert(original_cert.proof_success && corrected_cert.proof_success);
assert(original_cert.fixed_parameters && corrected_cert.fixed_parameters);
assert(original.newton_steps==0 && corrected.newton_steps>0);
assert(isequal(original.u,corrected.initial_u) && original.omega==corrected.initial_omega,...
    'Corrected run must start from the original certified candidate.');
assert(isequal(original.phase,corrected.phase) && original.phase_target==corrected.phase_target,...
    'Containment requires the identical phase slice.');
assert(original.reference_omega==corrected.reference_omega);
for key={'feedback','damping','delay','exponent','nu','norm'}
    assert(isequal(original_cert.(key{1}),corrected_cert.(key{1})),...
        'Certificates must use identical equations and norm.');
end
N=(length(original.u)-1)/2;
weights=intval('1.01').^abs((-N:N)');
center_distance=abs(intval(corrected.omega)-intval(original.omega)) + ...
    sum(abs(intval(corrected.u)-intval(original.u)).*weights);
% Decimal intervals match the radii used by the actual existence proofs.
contained_radius=center_distance+intval(corrected_cert.radius_decimal);
assert(sup(contained_radius)<inf(intval(original_cert.radius_decimal)),...
    'Refined proof ball is not contained in the original proof ball.');
summary=struct('proof_success',true,'same_orbit_as_original',true,...
    'phase_slice_identical',true,'fixed_parameters',true,...
    'center_distance_upper',sup(center_distance),...
    'refined_ball_distance_from_original_upper',sup(contained_radius),...
    'original_radius_decimal',original_cert.radius_decimal,...
    'refined_radius_decimal',corrected_cert.radius_decimal,...
    'true_system_newton_steps',corrected.newton_steps,...
    'period_lower',corrected_cert.period_lower,'period_upper',corrected_cert.period_upper,...
    'Y_upper',corrected_cert.Y_upper,'Z0_upper',corrected_cert.Z0_upper,...
    'C_upper',corrected_cert.C_upper,...
    'radii_polynomial_upper',corrected_cert.radii_polynomial_upper,...
    'contraction_upper',corrected_cert.contraction_upper,...
    'complete_infinite_tail',corrected_cert.complete_infinite_tail,...
    'interval_arithmetic','INTLAB 13');
fid=fopen(fullfile(refinement_out,'newton_refinement_summary.json'),'w');
fprintf(fid,'%s\n',jsonencode(summary,PrettyPrint=true));fclose(fid);
save(fullfile(refinement_out,'newton_refinement_containment.mat'),...
    'center_distance','contained_radius','summary');
disp(summary)
